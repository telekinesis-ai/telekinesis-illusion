"""View the project's generated dataset in FiftyOne.

Auto-detects which of the five layouts DATASET_DIR holds:
- "merged": project-native pre-split bag — `merged_coco_annotations.json` at
  the root with per-shard `shard_*/{coco_annotations.json, images/}` subdirs.
  This is what `BinPickingWorker.merge_shards()` produces.
- "shard": a single shard directory with `coco_annotations.json` and an
  `images/` subdir (one of the `shard_*` folders inside a merged dataset).
- "coco": split COCO with per-split `_annotations.coco.json` (output of
  `DatasetConverter` in `coco` mode).
- "yolo": Ultralytics YOLO segmentation layout with `data.yaml` at the root
  (output of `DatasetConverter` in `yolo` mode).
- "bop": BOP (Benchmark for 6D Object Pose Estimation) layout with numbered
  scene directories (e.g. 000001/) each containing `scene_gt_coco.json` and
  image subdirectories (rgb/ or gray/).  Scenes may sit directly under the
  root or under split directories (train/, val/, test/).
"""

import json
import shutil
import tempfile
from pathlib import Path
from typing import cast

import yaml
from PIL import Image
from pycocotools import mask as mask_utils

import fiftyone as fo
import fiftyone.core.labels as fol
import fiftyone.types as fot
from fiftyone import ViewField as F

# Point this at a dataset generated by one of the quickstart examples, e.g.
# "output/synthetic_data_<timestamp>" as produced by quickstart_flying_things.py
# or quickstart_parts_in_bin.py.
DATASET_DIR = Path(r"absolute/path/to/output/synthetic_data_<timestamp>")
DATASET_NAME = "illusion_dataset"
MAX_SAMPLES: int | None = None  # Set to e.g. 100 to view a random subset
COCO_ANNOTATIONS = "_annotations.coco.json"
SHARD_COCO_ANNOTATIONS = "coco_annotations.json"
MERGED_COCO_ANNOTATIONS = "merged_coco_annotations.json"
YOLO_DATA_YAML = "data.yaml"
BOP_SCENE_GT_COCO = "scene_gt_coco.json"
SPLIT_NAMES = ("train", "valid", "test")
# YOLOv5 data.yaml uses "val" as the validation key while our converter writes
# samples into a "valid/" directory; map yaml key -> tag we use everywhere else.
YOLO_YAML_KEY_TO_TAG = {"train": "train", "val": "valid", "test": "test"}
# BOP uses "val" as well; same mapping pattern.
BOP_SPLIT_NAMES = ("train", "val", "test")
BOP_SPLIT_TAG = {"train": "train", "val": "valid", "test": "test"}


def _coco_split_dirs(root: Path) -> list[tuple[str | None, Path]]:
    """Return [(tag, dir), ...] for either a multi-split root or a single split."""
    if (root / COCO_ANNOTATIONS).is_file():
        return [(None, root)]
    splits: list[tuple[str | None, Path]] = [
        (s, root / s)
        for s in SPLIT_NAMES
        if (root / s / COCO_ANNOTATIONS).is_file()
    ]
    if not splits:
        raise FileNotFoundError(
            f"No COCO data found at {root}. Expected either {COCO_ANNOTATIONS} "
            f"directly inside, or one of {SPLIT_NAMES} subdirs containing it."
        )
    return splits


def _is_bop_scene(d: Path) -> bool:
    return d.is_dir() and d.name.isdigit() and (d / BOP_SCENE_GT_COCO).is_file()


def _bop_scene_dirs(root: Path) -> list[tuple[str | None, Path]]:
    """Return [(tag, scene_dir), ...] for a BOP dataset.

    Scenes may sit directly under *root* or under split subdirectories
    (train/, val/, test/).
    """
    # Scenes directly under root (no splits).
    scenes = sorted((None, d) for d in root.iterdir() if _is_bop_scene(d))
    if scenes:
        return scenes

    # Scenes under split subdirectories.
    scenes = []
    for split_name in BOP_SPLIT_NAMES:
        split_dir = root / split_name
        if not split_dir.is_dir():
            continue
        tag = BOP_SPLIT_TAG[split_name]
        scenes.extend(
            sorted((tag, d) for d in split_dir.iterdir() if _is_bop_scene(d))
        )
    if not scenes:
        raise FileNotFoundError(
            f"No BOP scenes found at {root}. Expected numbered subdirectories "
            f"containing {BOP_SCENE_GT_COCO}, either directly or under "
            f"{BOP_SPLIT_NAMES} split dirs."
        )
    return scenes


def _detect_format(root: Path) -> str:
    if (root / MERGED_COCO_ANNOTATIONS).is_file():
        return "merged"
    if (root / SHARD_COCO_ANNOTATIONS).is_file() and (root / "images").is_dir():
        return "shard"
    if (root / YOLO_DATA_YAML).is_file():
        return "yolo"
    if (root / COCO_ANNOTATIONS).is_file() or any(
        (root / s / COCO_ANNOTATIONS).is_file() for s in SPLIT_NAMES
    ):
        return "coco"
    search_dirs = [root] + [
        root / s for s in BOP_SPLIT_NAMES if (root / s).is_dir()
    ]
    if any(
        _is_bop_scene(d) for p in search_dirs for d in p.iterdir() if d.is_dir()
    ):
        return "bop"
    raise FileNotFoundError(
        f"No recognizable dataset at {root}. Expected {MERGED_COCO_ANNOTATIONS} "
        f"(merged), {SHARD_COCO_ANNOTATIONS} + images/ (shard), {YOLO_DATA_YAML} "
        f"(YOLO), {COCO_ANNOTATIONS} at root or in {SPLIT_NAMES} (COCO), "
        f"or numbered scene dirs with {BOP_SCENE_GT_COCO} (BOP)."
    )


def _yolo_base_path(yaml_path: Path, data_yaml: dict[str, object]) -> Path:
    raw = data_yaml.get("path")
    base = Path(raw) if isinstance(raw, str) else yaml_path.parent
    if not base.is_absolute():
        base = (yaml_path.parent / base).resolve()
    return base


def _import_coco(
    dataset: fo.Dataset, root: Path, max_samples: int | None = None
) -> None:
    for tag, split_dir in _coco_split_dirs(root):
        dataset.add_dir(
            dataset_type=fot.COCODetectionDataset,
            data_path=str(split_dir),
            labels_path=str(split_dir / COCO_ANNOTATIONS),
            tags=[tag] if tag else None,
            label_field="ground_truth",
            max_samples=max_samples,
        )


def _import_merged(
    dataset: fo.Dataset, root: Path, max_samples: int | None = None
) -> None:
    """Import the project's pre-split bag via the merged COCO file.

    The merged JSON has `file_name` entries relative to *root* (e.g.
    `shard_xxx/images/000001.png`), so we point FiftyOne's COCO importer
    at *root* as `data_path` and let it resolve images itself.
    """
    dataset.add_dir(
        dataset_type=fot.COCODetectionDataset,
        data_path=str(root),
        labels_path=str(root / MERGED_COCO_ANNOTATIONS),
        label_field="ground_truth",
        max_samples=max_samples,
    )


def _import_shard(
    dataset: fo.Dataset, root: Path, max_samples: int | None = None
) -> None:
    """Import a single shard (`<shard_dir>/coco_annotations.json` + `images/`)."""
    dataset.add_dir(
        dataset_type=fot.COCODetectionDataset,
        data_path=str(root),
        labels_path=str(root / SHARD_COCO_ANNOTATIONS),
        label_field="ground_truth",
        max_samples=max_samples,
    )


_BROWSER_INCOMPATIBLE_EXTS = {".tif", ".tiff"}


def _import_bop(
    dataset: fo.Dataset, root: Path, max_samples: int | None = None
) -> Path | None:
    """Import a BOP dataset (one scene_gt_coco.json per scene directory).

    Parses COCO JSON manually instead of using FiftyOne's COCO importer to
    avoid decoding heavy RLE segmentation masks which can exhaust memory on
    large BOP datasets.  TIFF images are converted to PNG in a temp directory
    because browsers cannot display TIFF natively.
    """
    cache_dir: Path | None = None
    total_added = 0

    for tag, scene_dir in _bop_scene_dirs(root):
        with open(scene_dir / BOP_SCENE_GT_COCO, "r", encoding="utf-8") as f:
            coco = json.load(f)

        cat_map = {c["id"]: c["name"] for c in coco.get("categories", [])}
        img_info = {img["id"]: img for img in coco.get("images", [])}

        anns_by_img: dict[int, list[dict]] = {}
        for ann in coco.get("annotations", []):
            anns_by_img.setdefault(ann["image_id"], []).append(ann)

        samples: list[fo.Sample] = []
        for img_id, img in img_info.items():
            src = Path(scene_dir / img["file_name"])
            if src.suffix.lower() in _BROWSER_INCOMPATIBLE_EXTS:
                if cache_dir is None:
                    cache_dir = Path(tempfile.mkdtemp(prefix="fiftyone_bop_"))
                    print(
                        f"Converting TIFF images for browser display → {cache_dir}"
                    )
                png_path = cache_dir / scene_dir.name / (src.stem + ".png")
                png_path.parent.mkdir(parents=True, exist_ok=True)
                if not png_path.exists():
                    Image.open(src).save(png_path)
                filepath = str(png_path)
            else:
                filepath = str(src)
            w, h = img["width"], img["height"]

            detections = []
            for ann in anns_by_img.get(img_id, []):
                x, y, bw, bh = ann["bbox"]  # COCO: [x, y, w, h] in pixels
                xi, yi = round(x), round(y)
                bwi, bhi = round(bw), round(bh)

                instance_mask = None
                seg = ann.get("segmentation")
                if seg:
                    if isinstance(seg, dict) and "counts" in seg:
                        rle = seg
                        if isinstance(rle["counts"], list):
                            rle = mask_utils.frPyObjects(rle, h, w)
                    elif isinstance(seg, list):
                        rle = mask_utils.merge(
                            mask_utils.frPyObjects(seg, h, w)
                        )
                    else:
                        rle = None
                    if rle is not None:
                        full_mask = mask_utils.decode(rle)
                        instance_mask = full_mask[
                            yi : yi + bhi, xi : xi + bwi
                        ].astype(bool)

                detections.append(
                    fo.Detection(
                        label=cat_map.get(
                            ann["category_id"], str(ann["category_id"])
                        ),
                        bounding_box=[x / w, y / h, bw / w, bh / h],
                        mask=instance_mask,
                    )
                )

            sample = fo.Sample(filepath=filepath, tags=[tag] if tag else [])
            sample["ground_truth"] = fo.Detections(detections=detections)
            samples.append(sample)
            if (
                max_samples is not None
                and total_added + len(samples) >= max_samples
            ):
                break

        if max_samples is not None:
            samples = samples[: max_samples - total_added]
        dataset.add_samples(samples)
        total_added += len(samples)
        if max_samples is not None and total_added >= max_samples:
            break

    return cache_dir


IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp"}


def _import_yolo(
    dataset: fo.Dataset, root: Path, max_samples: int | None = None
) -> None:
    """Custom loader for Ultralytics YOLO segmentation labels (polygon per line).

    `fo.types.YOLOv5Dataset` only parses 5-value bbox lines, so we read the
    `<id>.txt` files ourselves and emit `fo.Polylines` (closed, filled).
    """
    yaml_path = root / YOLO_DATA_YAML
    with open(yaml_path, "r", encoding="utf-8") as f:
        data_yaml = yaml.safe_load(f) or {}
    base = _yolo_base_path(yaml_path, data_yaml)

    raw_names = data_yaml.get("names")
    if isinstance(raw_names, dict):
        class_names: list[str] = [
            str(raw_names[k]) for k in sorted(raw_names.keys())
        ]
    elif isinstance(raw_names, list):
        class_names = [str(n) for n in raw_names]
    else:
        raise ValueError(f"{yaml_path} is missing a usable 'names' entry")

    yaml_keys = [k for k in YOLO_YAML_KEY_TO_TAG if k in data_yaml]
    if not yaml_keys:
        raise FileNotFoundError(
            f"{yaml_path} has none of the expected split keys "
            f"{tuple(YOLO_YAML_KEY_TO_TAG)}; got {list(data_yaml)}."
        )

    total_added = 0
    for yaml_key in yaml_keys:
        rel = data_yaml[yaml_key]
        if not isinstance(rel, str):
            continue
        images_dir = (base / rel).resolve()
        labels_dir = images_dir.parent / "labels"
        tag = YOLO_YAML_KEY_TO_TAG[yaml_key]

        samples: list[fo.Sample] = []
        for img_path in sorted(images_dir.iterdir()):
            if img_path.suffix.lower() not in IMAGE_EXTS:
                continue
            label_path = labels_dir / f"{img_path.stem}.txt"
            polylines = _parse_yolo_seg_label(label_path, class_names)
            sample = fo.Sample(filepath=str(img_path), tags=[tag])
            sample["ground_truth"] = fo.Polylines(polylines=polylines)
            samples.append(sample)
            if (
                max_samples is not None
                and total_added + len(samples) >= max_samples
            ):
                break
        if max_samples is not None:
            samples = samples[: max_samples - total_added]
        dataset.add_samples(samples)
        total_added += len(samples)
        if max_samples is not None and total_added >= max_samples:
            break


def _parse_yolo_seg_label(
    label_path: Path, class_names: list[str]
) -> list[fo.Polyline]:
    if not label_path.is_file():
        return []
    polylines: list[fo.Polyline] = []
    with open(label_path, "r", encoding="utf-8") as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) < 1 + 2 * 3:  # class + at least 3 (x, y) points
                continue
            try:
                class_idx = int(parts[0])
                coords = [float(x) for x in parts[1:]]
            except ValueError:
                continue
            if len(coords) % 2 != 0:
                continue
            points = list(zip(coords[0::2], coords[1::2]))
            label = (
                class_names[class_idx]
                if 0 <= class_idx < len(class_names)
                else str(class_idx)
            )
            polylines.append(
                fo.Polyline(
                    label=label,
                    points=[points],
                    closed=True,
                    filled=True,
                )
            )
    return polylines


def main() -> None:
    fo.app_config.color_by = "instance"

    if fo.dataset_exists(DATASET_NAME):
        fo.delete_dataset(DATASET_NAME)

    dataset = fo.Dataset(DATASET_NAME)
    fmt = _detect_format(DATASET_DIR)
    print(f"Detected dataset format: {fmt}")
    bop_cache_dir: Path | None = None
    if fmt == "yolo":
        _import_yolo(dataset, DATASET_DIR, max_samples=MAX_SAMPLES)
    elif fmt == "merged":
        _import_merged(dataset, DATASET_DIR, max_samples=MAX_SAMPLES)
    elif fmt == "shard":
        _import_shard(dataset, DATASET_DIR, max_samples=MAX_SAMPLES)
    elif fmt == "bop":
        bop_cache_dir = _import_bop(
            dataset, DATASET_DIR, max_samples=MAX_SAMPLES
        )
    else:
        _import_coco(dataset, DATASET_DIR, max_samples=MAX_SAMPLES)

    dataset.persistent = True

    label_field_subfield = {
        fol.Detections: "detections",
        fol.Polylines: "polylines",
    }
    label_field_name: str | None = None
    label_field_subfield_name: str | None = None
    for name, field in dataset.get_field_schema().items():
        if not isinstance(field, fo.EmbeddedDocumentField):
            continue
        for label_type, subfield in label_field_subfield.items():
            if issubclass(field.document_type, label_type):
                label_field_name = name
                label_field_subfield_name = subfield
                break
        if label_field_name is not None:
            break
    if label_field_name is None or label_field_subfield_name is None:
        raise RuntimeError(
            f"No Detections/Polylines field found in dataset. Schema: "
            f"{list(dataset.get_field_schema().keys())}"
        )

    n_samples = cast(int, dataset.count())
    split_counts = cast(dict[str, int], dataset.count_sample_tags())
    label_path = f"{label_field_name}.{label_field_subfield_name}.label"
    total_counts = cast(dict[str, int], dataset.count_values(label_path))
    splits_present = [s for s in SPLIT_NAMES if s in split_counts]
    per_split: dict[str, dict[str, int]] = {
        s: cast(dict[str, int], dataset.match_tags(s).count_values(label_path))
        for s in splits_present
    }

    print(f"\nDataset: {dataset.name} ({n_samples} samples)")
    print("\nSamples per split:")
    for split, count in sorted(split_counts.items()):
        print(f"  {split:6s} {count}")

    images_with: dict[str, int] = {
        lb: cast(int, dataset.match(F(label_path).contains([lb])).count())
        for lb in total_counts
    }

    print(f"\nClass distribution ({label_field_name}):")
    print(
        "  Columns: train/valid/test cells show count/share-of-split% "
        "(each column sums to 100%);\n"
        "           total = instances across all splits;\n"
        "           images = distinct images containing >=1 instance of the class;\n"
        "           % = class instances as share of grand total."
    )
    label_w = max((len(lb) for lb in total_counts), default=5)
    label_w = max(label_w, len("class"))
    col_w_split = 12
    col_w = 8
    grand_total = sum(total_counts.values())
    split_totals = {s: sum(per_split[s].values()) for s in splits_present}

    header = f"  {'class':<{label_w}}"
    for s in splits_present:
        header += f" {s:>{col_w_split}}"
    for c in ("total", "images", "%"):
        header += f" {c:>{col_w}}"
    print(header)
    dash_w = label_w + (col_w_split + 1) * len(splits_present) + (col_w + 1) * 3
    print("  " + "-" * dash_w)

    for label, _ in sorted(total_counts.items(), key=lambda kv: -kv[1]):
        row = f"  {label:<{label_w}}"
        class_total = total_counts[label]
        for s in splits_present:
            c = per_split[s].get(label, 0)
            col_total = split_totals[s]
            col_pct = round(c / col_total * 100) if col_total else 0
            row += f" {f'{c}/{col_pct}%':>{col_w_split}}"
        row += f" {class_total:>{col_w}}"
        row += f" {images_with[label]:>{col_w}}"
        pct = (class_total / grand_total * 100) if grand_total else 0.0
        row += f" {pct:>{col_w - 1}.1f}%"
        print(row)

    totals_row = f"  {'TOTAL':<{label_w}}"
    for s in splits_present:
        totals_row += f" {f'{split_totals[s]}/100%':>{col_w_split}}"
    totals_row += f" {grand_total:>{col_w}}"
    totals_row += f" {n_samples:>{col_w}}"
    totals_row += f" {100.0:>{col_w - 1}.1f}%"
    print(totals_row)
    print(
        "\nFor interactive in-app charts: in the FiftyOne app, click '+' next "
        "to the 'Samples' tab and add a 'Histograms' panel.\n"
    )

    session = fo.launch_app(dataset)
    assert session is not None
    try:
        session.wait()
    except KeyboardInterrupt:
        pass
    finally:
        if bop_cache_dir is not None:
            shutil.rmtree(bop_cache_dir, ignore_errors=True)
            print(f"Cleaned up temp image cache: {bop_cache_dir}")


if __name__ == "__main__":
    main()
